static const uint8_t *get_glyph(char c)
{
    if (c < 32 || c > 126)
        return font8x8[0];
    return font8x8[c - 32];
}

static void scroll_up()
{
    uint32_t row_bytes = fb.pitch * 8;
    uint8_t *dst = fb.buffer;
    uint8_t *src = fb.buffer + row_bytes;
    uint32_t total = fb.pitch * fb.height;

    for (uint32_t i = 0; i < total - row_bytes; i++)
        dst[i] = src[i];

    for (uint32_t i = total - row_bytes; i < total; i++)
        dst[i] = 0;
}

// --- Public API ---

bool gpu::init(uint32_t width, uint32_t height)
{
    mailbox::buffer[0] = 35 * 4;
    mailbox::buffer[1] = MAILBOX_REQUEST;

    mailbox::buffer[2] = TAG_SET_PHYS_WH;
    mailbox::buffer[3] = 8;
    mailbox::buffer[4] = 0;
    mailbox::buffer[5] = width;
    mailbox::buffer[6] = height;

    mailbox::buffer[7] = TAG_SET_VIRT_WH;
    mailbox::buffer[8] = 8;
    mailbox::buffer[9] = 0;
    mailbox::buffer[10] = width;
    mailbox::buffer[11] = height;

    mailbox::buffer[12] = TAG_SET_VIRT_OFFSET;
    mailbox::buffer[13] = 8;
    mailbox::buffer[14] = 0;
    mailbox::buffer[15] = 0;
    mailbox::buffer[16] = 0;

    mailbox::buffer[17] = TAG_SET_DEPTH;
    mailbox::buffer[18] = 4;
    mailbox::buffer[19] = 0;
    mailbox::buffer[20] = 32;

    mailbox::buffer[21] = TAG_SET_PIXEL_ORDER;
    mailbox::buffer[22] = 4;
    mailbox::buffer[23] = 0;
    mailbox::buffer[24] = 1;

    mailbox::buffer[25] = TAG_ALLOCATE_FB;
    mailbox::buffer[26] = 8;
    mailbox::buffer[27] = 0;
    mailbox::buffer[28] = 4096;
    mailbox::buffer[29] = 0;

    mailbox::buffer[30] = TAG_GET_PITCH;
    mailbox::buffer[31] = 4;
    mailbox::buffer[32] = 0;
    mailbox::buffer[33] = 0;

    mailbox::buffer[34] = TAG_END;

    if (!mailbox::call(MAILBOX_CH_PROP) || mailbox::buffer[20] != 32)
        return false;

    fb.buffer = (uint8_t *)(uintptr_t)(mailbox::buffer[28] & 0x3FFFFFFF);
    fb.width = mailbox::buffer[5];
    fb.height = mailbox::buffer[6];
    fb.pitch = mailbox::buffer[33];
    fb.depth = mailbox::buffer[20];

    if (fb.buffer == nullptr)
        return false;

    max_cols = fb.width / 8;
    max_rows = fb.height / 8;
    cursor_col = 0;
    cursor_row = 0;

    gpu::clear(COLOR_BLACK);

    return true;
}

Framebuffer *gpu::get_fb()
{
    return &fb;
}

void gpu::put_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb.width || y >= fb.height)
        return;
    uint32_t offset = y * fb.pitch + x * (fb.depth / 8);
    *(uint32_t *)(fb.buffer + offset) = color;
}

void gpu::fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t row = y; row < y + h && row < fb.height; row++)
        for (uint32_t col = x; col < x + w && col < fb.width; col++)
            put_pixel(col, row, color);
}

void gpu::clear(uint32_t color)
{
    for (uint32_t y = 0; y < fb.height; y++)
        for (uint32_t x = 0; x < fb.width; x++)
            put_pixel(x, y, color);
    cursor_col = 0;
    cursor_row = 0;
}

void gpu::set_cursor(uint32_t col, uint32_t row)
{
    cursor_col = col;
    cursor_row = row;
}

void gpu::put_char(char c, uint32_t color, uint32_t bg)
{
    if (c == '\n')
    {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= max_rows)
        {
            scroll_up();
            cursor_row = max_rows - 1;
        }
        return;
    }

    if (c == '\r')
    {
        cursor_col = 0;
        return;
    }

    const uint8_t *glyph = get_glyph(c);
    uint32_t px = cursor_col * 8;
    uint32_t py = cursor_row * 8;

    for (uint32_t row = 0; row < 8; row++)
    {
        for (uint32_t col = 0; col < 8; col++)
        {
            if (glyph[row] & (0x80 >> col))
                put_pixel(px + col, py + row, color);
            else
                put_pixel(px + col, py + row, bg);
        }
    }

    cursor_col++;
    if (cursor_col >= max_cols)
    {
        cursor_col = 0;
        cursor_row++;
        if (cursor_row >= max_rows)
        {
            scroll_up();
            cursor_row = max_rows - 1;
        }
    }
}

void gpu::print(const char *str, uint32_t color, uint32_t bg)
{
    for (size_t i = 0; str[i] != '\0'; i++)
        put_char(str[i], color, bg);
}

void gpu::print(const char *str)
{
    print(str, COLOR_WHITE, COLOR_BLACK);
}
